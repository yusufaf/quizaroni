import { readdirSync } from 'node:fs';
import { isAbsolute, join, relative, sep } from 'node:path';
import type { JournalEntry } from '../src/db/migrations';

export const TARGETS = [
    'linux-x64',
    'linux-arm64',
    'windows-x64',
    'darwin-x64',
    'darwin-arm64',
] as const;
export type Target = (typeof TARGETS)[number];

export function binaryFilename(target: Target): string {
    return `quizaroni-${target}${target.startsWith('windows') ? '.exe' : ''}`;
}

export function parseTargets(value: string | undefined): Target[] {
    if (value === undefined) return [...TARGETS];
    return value.split(',').map((raw) => {
        const target = raw.trim();
        if (!(TARGETS as readonly string[]).includes(target)) {
            throw new Error(
                `Unknown target "${target}"; expected one of ${TARGETS.join(', ')}`
            );
        }
        return target as Target;
    });
}

/** Every file under distDir, as sorted posix paths relative to it. */
export function collectWebFiles(distDir: string): string[] {
    const files = readdirSync(distDir, { recursive: true, withFileTypes: true })
        .filter((entry) => entry.isFile())
        .map((entry) =>
            relative(distDir, join(entry.parentPath, entry.name))
                .split(sep)
                .join('/')
        )
        .sort();
    if (!files.includes('index.html')) {
        throw new Error(
            `No index.html in ${distDir}; run pnpm build:web first`
        );
    }
    return files;
}

/** A relative import specifier from fromDir to file, with forward slashes. */
export function importSpecifier(fromDir: string, file: string): string {
    const rel = relative(fromDir, file);
    if (isAbsolute(rel)) {
        throw new Error(
            `Cannot import ${file} from ${fromDir} by a relative path (different drive?)`
        );
    }
    const posixRel = rel.split(sep).join('/');
    return posixRel.startsWith('../') ? posixRel : `./${posixRel}`;
}

export type EntryInput = {
    /** Import specifier of src/embedded.ts, relative to the entry's folder. */
    registry: string;
    /** Import specifier of src/index.ts. */
    main: string;
    webFiles: { url: string; specifier: string }[];
    migrations: (JournalEntry & { specifier: string })[];
};

// The bundle is registered before src/index.ts is imported, because index.ts
// reads it at the top level.
export function renderEntry(input: EntryInput): string {
    const q = JSON.stringify;
    const lines = [
        '// Generated by scripts/build-binary.ts; do not edit.',
        `import { setEmbeddedBundle } from ${q(input.registry)};`,
        ...input.webFiles.map(
            (f, i) =>
                `import web${i} from ${q(f.specifier)} with { type: "file" };`
        ),
        ...input.migrations.map(
            (m, i) =>
                `import sql${i} from ${q(m.specifier)} with { type: "text" };`
        ),
        'setEmbeddedBundle({',
        `    webFiles: new Map([${input.webFiles
            .map((f, i) => `[${q(f.url)}, web${i}]`)
            .join(', ')}]),`,
        `    migrations: [${input.migrations
            .map(
                (m, i) =>
                    `{ tag: ${q(m.tag)}, when: ${m.when}, breakpoints: ${m.breakpoints}, sql: sql${i} }`
            )
            .join(', ')}],`,
        '});',
        `await import(${q(input.main)});`,
        '',
    ];
    return lines.join('\n');
}
